"""Optional maintainer browser acceptance. Requires Playwright only in the test environment."""
import json, pathlib, time, threading, http.server, functools, sys
from playwright.sync_api import sync_playwright
ROOT=pathlib.Path(__file__).resolve().parents[1]
OUT=ROOT/'evidence'; OUT.mkdir(exist_ok=True)
handler=functools.partial(http.server.SimpleHTTPRequestHandler,directory=str(ROOT/'docs'))
server=http.server.ThreadingHTTPServer(('127.0.0.1',0),handler)
threading.Thread(target=server.serve_forever,daemon=True).start()
base=f'http://127.0.0.1:{server.server_port}'
results=[]
def check(name,condition):
    if not condition: raise AssertionError(name)
    results.append({'name':name,'passed':True})
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1512,'height':1100})
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    try:
        page.goto(base+'/v3/index.html',wait_until='networkidle')
    except Exception as e:
        (OUT/'v3-browser-results.json').write_text(json.dumps({'method':'direct-navigation','blocked':True,'reason':str(e).splitlines()[0],'checks':results},indent=2))
        print('DIRECT_NAVIGATION_BLOCKED',str(e).splitlines()[0]);browser.close();server.shutdown();sys.exit(2)
    check('studio loads',page.get_by_role('heading',name='Give your idea room to grow.').count()==1)
    page.get_by_role('button',name='A focused dashboard').click()
    check('authored example is explicitly labeled',page.locator('#messages').inner_text().find('authored example')>=0)
    check('dark sidebar rendered',page.locator('.v3-app.dark[data-navigation="sidebar"]').count()==1)
    page.get_by_role('button',name='+ Add record',exact=True).click()
    page.get_by_label('Task *',exact=True).fill('Ship the working prototype')
    page.get_by_label('Status *',exact=True).select_option('In progress')
    page.get_by_label('Due date',exact=True).fill('2026-01-01')
    page.get_by_role('button',name='Save record',exact=True).click()
    check('record creation in composable board',page.locator('.v3-record-card').count()==1)
    check('overdue unfinished record highlighted',page.locator('.v3-record-card.v3-highlight').count()==1)
    page.get_by_role('button',name='+ Add record',exact=True).click()
    page.get_by_label('Task *',exact=True).fill('Take a small first step')
    page.get_by_label('Status *',exact=True).select_option('Done')
    page.get_by_role('button',name='Save record',exact=True).click()
    check('computed completion is 50 percent',page.locator('[data-node="done-card"]').inner_text().endswith('50%'))
    page.screenshot(path=str(OUT/'v3-dashboard-desktop.png'),full_page=True)
    page.get_by_role('button',name='Focus',exact=True).click()
    check('Focus filters completed tasks',page.locator('.v3-record-card').count()==1)
    page.reload(wait_until='networkidle')
    check('app, navigation and records persist after reload',page.locator('.v3-record-card').count()==1 and 'Ship the working prototype' in page.locator('.v3-record-card').inner_text())
    check('conversation survives page reload','authored example' in page.locator('#messages').inner_text())
    page.get_by_role('button',name='Overview',exact=True).click()
    page.get_by_role('button',name='Edit',exact=True).first.click()
    page.get_by_label('Status *',exact=True).select_option('Done')
    page.get_by_role('button',name='Save record',exact=True).click()
    check('completion recalculates after record edit',page.locator('[data-node="done-card"]').inner_text().endswith('100%'))
    check('completed tasks are not highlighted',page.locator('.v3-record-card.v3-highlight').count()==0)
    page.set_viewport_size({'width':390,'height':844})
    page.screenshot(path=str(OUT/'v3-dashboard-mobile.png'),full_page=True)
    check('mobile document does not overflow',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    check('mobile app shell stacks navigation',page.locator('.v3-app').evaluate('(e)=>getComputedStyle(e).flexDirection')=='column')
    page.set_viewport_size({'width':1512,'height':1100})
    page.on('dialog',lambda d:d.accept())
    page.get_by_role('button',name='A little curiosity').click()
    page.screenshot(path=str(OUT/'v3-quiz-desktop.png'),full_page=True)
    check('quiz is composition, not CRUD',page.locator('[data-node="question-text"]').count()==1 and page.locator('.v3-records').count()==0)
    for answer in ['Mars','36','Red']:
        page.get_by_label('Your answer',exact=True).select_option(answer)
        page.get_by_role('button',name='Check my answer',exact=True).click()
        check('answer feedback displayed '+answer,page.locator('[data-node="feedback-text"]').count()==1)
        check('duplicate scoring blocked '+answer,page.get_by_role('button',name='Check my answer',exact=True).is_disabled())
        page.get_by_role('button',name='Continue →',exact=True).click()
    check('quiz final score',page.locator('[data-node="results-score"]').inner_text().endswith('2 / 3'))
    page.reload(wait_until='networkidle')
    check('quiz state persists on reload',page.locator('[data-node="results-score"]').inner_text().endswith('2 / 3'))
    page.get_by_role('button',name='Try again',exact=True).click()
    check('quiz restarts',page.locator('[data-node="question-count"]').inner_text()=='Question 1 of 3')
    # Download is checked from the studio; this does not open the exported file.
    with page.expect_download() as info:page.get_by_role('button',name='Get app ↗',exact=True).click()
    download=info.value;download.save_as(str(OUT/'v3-quiz-export.html'))
    exported=(OUT/'v3-quiz-export.html').read_text()
    check('export excludes provider connection and record snapshots','api.groq.com' not in exported and 'GROQ_API_KEY' not in exported and "connect-src 'none'" in exported)
    check('no uncaught browser errors',not errors)
    browser.close()
server.shutdown()
(OUT/'v3-browser-results.json').write_text(json.dumps({'method':'direct HTTP navigation, real browser storage and reload; Chromium','checks':results,'errors':errors},indent=2))
print(json.dumps({'passed':len(results),'method':'direct navigation'}))
