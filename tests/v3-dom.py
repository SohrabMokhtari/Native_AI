"""Restricted-environment checks: injected local assets, fake storage and API; no policy changes."""
import json,pathlib,re,subprocess
from playwright.sync_api import sync_playwright
ROOT=pathlib.Path(__file__).resolve().parents[1];OUT=ROOT/'evidence'
subprocess.run(['node','tests/v3-bundle.mjs'],cwd=ROOT,check=True)
markup=(ROOT/'docs/v3/index.html').read_text()
markup=re.sub(r'<script\b[^>]*>.*?</script>','',markup,flags=re.S)
markup=re.sub(r'<link[^>]*rel="stylesheet"[^>]*>','',markup)
css=(ROOT/'docs/v3/studio.css').read_text();bundle=(OUT/'v3-test-bundle.js').read_text()
results=[]
def check(name,value):
    if not value:raise AssertionError(name)
    results.append({'name':name,'passed':True})
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1512,'height':1100});errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.evaluate("""() => {const memory=new Map();Object.defineProperty(window,'localStorage',{configurable:true,value:{getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,String(v)),removeItem:k=>memory.delete(k),clear:()=>memory.clear()}});window.fetch=async()=>new Response(JSON.stringify({mode:'disabled'}),{status:200,headers:{'Content-Type':'application/json'}});} """)
    def boot():
        page.set_content(markup);page.add_style_tag(content=css);page.add_script_tag(content=bundle)
    boot()
    check('studio renders from local assets',page.get_by_role('heading',name='Give your idea room to grow.').count()==1)
    page.get_by_role('button',name='A focused dashboard').click()
    check('example is labeled authored, not AI', 'authored example' in page.locator('#messages').inner_text())
    check('dark sidebar renderer',page.locator('.v3-app.dark[data-navigation="sidebar"]').count()==1)
    for title,status,due in [('Ship the working prototype','In progress','2026-01-01'),('Take a small first step','Done',''),('Plan the next experiment','To do','')]:
        page.get_by_role('button',name='+ Add record',exact=True).click()
        page.get_by_label('Task *',exact=True).fill(title);page.get_by_label('Status *',exact=True).select_option(status)
        if due:page.get_by_label('Due date',exact=True).fill(due)
        page.get_by_role('button',name='Save record',exact=True).click()
    check('create three records',page.locator('.v3-record-card').count()==3)
    check('conditional overdue styling',page.locator('.v3-record-card.v3-highlight').count()==1)
    check('computed progress',page.locator('[data-node="done-card"]').inner_text().endswith('33%'))
    page.screenshot(path=str(OUT/'v3-dashboard-desktop.png'),full_page=True)
    page.get_by_role('button',name='Focus',exact=True).click();check('Focus filters completed tasks',page.locator('.v3-record-card').count()==2)
    boot();check('simulated storage survives studio remount',page.locator('.v3-record-card').count()==2)
    check('conversation restored from simulated storage','authored example' in page.locator('#messages').inner_text())
    page.get_by_role('button',name='Overview',exact=True).click()
    page.locator('.v3-highlight').get_by_role('button',name='Edit',exact=True).click()
    page.get_by_label('Status *',exact=True).select_option('Done');page.get_by_role('button',name='Save record',exact=True).click()
    check('progress recalculates after status change',page.locator('[data-node="done-card"]').inner_text().endswith('67%'))
    check('completed record loses overdue styling',page.locator('.v3-highlight').count()==0)
    page.set_viewport_size({'width':390,'height':844});page.screenshot(path=str(OUT/'v3-dashboard-mobile.png'),full_page=True)
    check('mobile has no page overflow',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    check('mobile sidebar stacks above content',page.locator('.v3-app').evaluate('(e)=>getComputedStyle(e).flexDirection')=='column')
    page.set_viewport_size({'width':1512,'height':1100});page.on('dialog',lambda d:d.accept());page.get_by_role('button',name='A little curiosity').click()
    page.screenshot(path=str(OUT/'v3-quiz-desktop.png'),full_page=True)
    check('quiz uses same runtime without a collection component',page.locator('[data-node="question-text"]').count()==1 and page.locator('.v3-records').count()==0)
    for answer in ['Mars','36','Red']:
        page.get_by_label('Your answer',exact=True).select_option(answer);page.get_by_role('button',name='Check my answer',exact=True).click()
        check('feedback visible '+answer,page.locator('[data-node="feedback-text"]').count()==1)
        check('duplicate scoring disabled '+answer,page.get_by_role('button',name='Check my answer',exact=True).is_disabled())
        page.get_by_role('button',name='Continue →',exact=True).click()
    check('quiz score 2 of 3',page.locator('[data-node="results-score"]').inner_text().endswith('2 / 3'))
    boot();check('quiz state restores from simulated storage',page.locator('[data-node="results-score"]').inner_text().endswith('2 / 3'))
    page.get_by_role('button',name='Try again',exact=True).click();check('quiz reset action',page.locator('[data-node="question-count"]').inner_text()=='Question 1 of 3')
    # Render the actual generated standalone artifact with outbound fetch forbidden.
    exported=(ROOT.parent/'native-ai-quiz-v3.html').read_text()
    page.evaluate("() => {window.fetch=async()=>{throw new Error('network forbidden in export test')};}")
    page.set_content(exported)
    check('standalone export renders shared interpreter',page.locator('[data-node="question-text"]').count()==1)
    page.get_by_label('Your answer',exact=True).select_option('Mars');page.get_by_role('button',name='Check my answer',exact=True).click()
    check('standalone quiz action works without model', 'Exactly right' in page.locator('[data-node="feedback-text"]').inner_text())
    check('no uncaught JavaScript errors',len(errors)==0)
    browser.close()
(OUT/'v3-dom-results.json').write_text(json.dumps({'method':'Injected local assets in blank Chromium page; isolated memory storage and config mock. NOT direct navigation, actual storage, reload, provider or deployment testing.','checks':results,'errors':errors},indent=2))
print(json.dumps({'passed':len(results),'method':'restricted DOM'}))
