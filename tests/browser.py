"""Maintainer acceptance tests. Requires Playwright only in the test environment."""
import json, pathlib, zipfile
from playwright.sync_api import sync_playwright
ROOT=pathlib.Path(__file__).resolve().parents[1]
OUT=ROOT/'evidence'
checks=[]
def record(name, condition=True):
    assert condition, name
    checks.append(name)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    context=browser.new_context(viewport={'width':1440,'height':1150},accept_downloads=True)
    page=context.new_page(); errors=[]
    page.on('pageerror',lambda error:errors.append(str(error)))
    page.goto('http://127.0.0.1:4322/',wait_until='networkidle')
    page.screenshot(path=str(OUT/'01-studio-desktop.png'),full_page=True)
    record('Studio labels offline mode honestly',page.locator('#mode').inner_text()=='Starter mode')
    page.locator('[data-prompt="Build a task board"]').click()
    page.locator('.native-app').wait_for()
    record('Plain-language task starter renders',page.locator('.na-intro h1').inner_text()=='Daylight')
    record('Boards display empty state before records',page.get_by_text('A fresh start',exact=True).count()==1)
    def add(title,status='To do',notes=''):
        page.get_by_role('button',name='+ Add record',exact=True).click()
        page.locator('.na-dialog input[name=title]').fill(title)
        page.locator('.na-dialog textarea[name=notes]').fill(notes)
        page.locator('.na-dialog select[name=status]').select_option(status)
        page.get_by_role('button',name='Save record',exact=True).click()
    add('Sketch the next big idea','In progress','Start with the one thing people need most.')
    add('Take a proper lunch break','To do','A little space makes better work.')
    add('Ship something useful','Done','Small, working, and ready to share.')
    record('Create records and board groups',page.locator('.na-card').count()==3 and page.locator('.na-column').count()==3)
    page.reload(wait_until='networkidle')
    record('Browser reload preserves app and records',page.locator('.na-card').count()==3)
    page.locator('#prompt').fill('Rename it My little workspace')
    page.locator('#prompt-form').evaluate('(f)=>f.requestSubmit()')
    page.wait_for_function("document.querySelector('.na-intro h1').textContent === 'My little workspace'")
    record('Conversational rename preserves records',page.locator('.na-card').count()==3)
    page.locator('#prompt').fill('Make it teal')
    page.locator('#prompt-form').evaluate('(f)=>f.requestSubmit()')
    page.wait_for_function("document.querySelector('.native-app').style.getPropertyValue('--app-accent') === '#087e80'")
    record('Conversational theme change works')
    page.locator('#prompt').fill('Add a text field called Owner')
    page.locator('#prompt-form').evaluate('(f)=>f.requestSubmit()')
    page.wait_for_function("JSON.parse(localStorage.getItem('native-ai-workspace-v2')).app.collections[0].fields.some(f=>f.id==='owner')")
    record('Optional field extension keeps records',page.locator('.na-card').count()==3)
    page.locator('#prompt').fill('Build a video editor with payments')
    page.locator('#prompt-form').evaluate('(f)=>f.requestSubmit()')
    record('Unsupported request does not replace the app',page.locator('.na-intro h1').inner_text()=='My little workspace')
    page.locator('.na-search').fill('proper lunch')
    record('Search filters the view',page.locator('.na-card').count()==1)
    page.locator('.na-search').fill('')
    page.locator('.na-card').filter(has_text='Take a proper lunch break').get_by_role('button',name='Edit',exact=True).click()
    page.locator('.na-dialog select[name=status]').select_option('Done')
    page.locator('.na-dialog input[name=owner]').fill('Me')
    page.get_by_role('button',name='Save record',exact=True).click()
    record('Record edit persists and moves board group',page.locator('.na-column').filter(has=page.get_by_role('heading',name='Done · 2',exact=True)).count()==1)
    page.screenshot(path=str(OUT/'02-app-desktop.png'),full_page=True)
    page.locator('#mobile').click()
    record('Mobile preview size control works','phone' in page.locator('#app-root').get_attribute('class'))
    page.screenshot(path=str(OUT/'03-phone-preview.png'),full_page=True)
    page.locator('#desktop').click()
    page.locator('#export').click()
    with page.expect_download() as info:page.locator('#download-html').click()
    info.value.save_as(str(OUT/'sample-app.html'))
    record('Standalone HTML downloads', (OUT/'sample-app.html').stat().st_size>1000)
    with page.expect_download() as info:page.locator('#download-pwa').click()
    info.value.save_as(str(OUT/'sample-app-web.zip'))
    with zipfile.ZipFile(OUT/'sample-app-web.zip') as z:
        record('PWA ZIP passes CRC verification',z.testzip() is None)
        record('PWA ZIP contains executable and mobile files',set(z.namelist())=={'index.html','manifest.webmanifest','icon.svg','sw.js','README.txt'})
        z.extractall(OUT/'pwa-export')
    with page.expect_download() as info:page.locator('#backup').click()
    info.value.save_as(str(OUT/'workspace-backup.native.json'))
    backup=json.loads((OUT/'workspace-backup.native.json').read_text())
    record('Explicit backup contains records',len(backup['data']['items'])==3)
    record('App export excludes private record values','Take a proper lunch break' not in (OUT/'sample-app.html').read_text())
    page.locator('#export-dialog .close').click()
    # XSS strings must be displayed as text, not executed or interpreted.
    add('<img src=x onerror="window.xss=true">','To do','</script><script>window.xss=true</script>')
    record('Untrusted record text is not executable',page.evaluate('window.xss !== true') and page.locator('.na-card img').count()==0)
    page.once('dialog',lambda d:d.accept())
    page.locator('.na-card').filter(has_text='<img src=x').get_by_role('button',name='Delete',exact=True).click()
    record('Delete record removes the intended item',page.locator('.na-card').count()==3)
    # An exported application runs with all network access disabled.
    offline=browser.new_context(viewport={'width':1100,'height':900},offline=True)
    standalone=offline.new_page();offline_errors=[];standalone.on('pageerror',lambda e:offline_errors.append(str(e)))
    standalone.goto((OUT/'sample-app.html').as_uri(),wait_until='load')
    record('Standalone export runs offline without installation',standalone.locator('.na-intro h1').inner_text()=='My little workspace')
    standalone.get_by_role('button',name='+ Add record',exact=True).click()
    standalone.locator('.na-dialog input[name=title]').fill('Offline record')
    standalone.get_by_role('button',name='Save record',exact=True).click()
    record('Offline exported app accepts records',standalone.locator('.na-card').count()==1)
    standalone.reload(wait_until='load')
    record('Standalone file persistence works in tested Chromium',standalone.locator('.na-card').count()==1)
    standalone.screenshot(path=str(OUT/'04-exported-app.png'),full_page=True)
    record('Standalone has no browser errors',not offline_errors)
    phone=browser.new_context(viewport={'width':390,'height':844},is_mobile=True,device_scale_factor=1)
    mobile=phone.new_page();mobile.goto('http://127.0.0.1:4322/',wait_until='networkidle')
    mobile.locator('[data-prompt="Build a reading list in teal"]').click();mobile.locator('.native-app').wait_for()
    record('Mobile studio has no horizontal overflow',mobile.evaluate('document.documentElement.scrollWidth <= window.innerWidth'))
    mobile.screenshot(path=str(OUT/'05-studio-mobile.png'),full_page=True)
    # Import an invalid model; the current app must stay intact.
    invalid=OUT/'invalid-backup.json';invalid.write_text('{"format":"native-ai-backup/1","app":{"script":"alert(1)"},"data":{}}')
    mobile.locator('#import-file').set_input_files(str(invalid))
    record('Invalid backup is rejected without replacing app',mobile.locator('.na-intro h1').inner_text()=='Next chapter')
    record('No uncaught browser errors during studio tests',not errors)
    browser.close()
(OUT/'browser-results.json').write_text(json.dumps({'passed':len(checks),'checks':checks,'method':'Real Chromium navigation to local HTTP server; standalone export opened via file:// with network disabled.','not_tested':['Real AI provider','Deployed Cloudflare Worker','Safari/iOS installation','App-store builds','Cross-device sync']},indent=2))
print(json.dumps({'passed':len(checks),'checks':checks},indent=2))
